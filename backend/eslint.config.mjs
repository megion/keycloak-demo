import eslint from '@eslint/js';
import tseslint from 'typescript-eslint';
// Turns off every ESLint rule that conflicts with Prettier's formatting.
import eslintConfigPrettier from 'eslint-config-prettier';
// Prettier as an ESLint rule: `prettier/prettier` reports formatting as a lint error,
// and `--fix` reformats the file using backend/.prettierrc. ESLint 10 rejects nested
// `extends`, so the plugin is registered explicitly instead of its config preset.
import prettierPlugin from 'eslint-plugin-prettier';

export default tseslint.config(
  // dist/ is compiled output (gitignored, generated by tsc); the config file itself is JS.
  { ignores: ['dist/**', 'node_modules/**', 'eslint.config.mjs'] },
  {
    files: ['src/**/*.ts', 'test/**/*.ts'],
    extends: [
      eslint.configs.recommended,
      tseslint.configs.recommended,
      tseslint.configs.stylistic,
      eslintConfigPrettier,
    ],
    plugins: { prettier: prettierPlugin },
    rules: {
      // Formatting is enforced as a lint error; Prettier reads backend/.prettierrc.
      'prettier/prettier': 'error',
      // The base rule does not understand TypeScript parameter properties (ApiError's
      // `public readonly status` / `public readonly code`), so the TS variant is used.
      'no-unused-vars': 'off',
      '@typescript-eslint/no-unused-vars': [
        'error',
        // Unused function parameters are prefixed with `_` (e.g. errorHandler's `_next`),
        // which is the convention this codebase uses.
        { argsIgnorePattern: '^_' },
      ],
    },
  },
);
